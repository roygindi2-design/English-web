#!/usr/bin/env node
/**
 * Builds supabase/seed/0002_word_cefr_levels.sql from the two CEFR profiles in data/
 * plus the batch files already ingested (T-010, closing half).
 *
 * ⛔ UPDATE only. This file never creates a word: an outside profile is not a licence
 *    to invent a headword, and a word that is not in `words` is a word the Content
 *    agent has not authored. If seed 0001 has not been applied, this file updates
 *    nothing and that is the correct outcome.
 *
 * ⛔ It never touches senses.cefr_level. Measured 2026-08-12 with the real modules:
 *    the profile band differs from the authored sense band on 125 of 343 rows
 *    (94 of the 306 distinct pairs). Both are true — one is a LEMMA claim from a
 *    published profile, the other a SENSE judgement of ours. So the profile lands in
 *    its own column, named for its provenance, and nothing merges them.
 *
 * ⛔ TD-24: the output is a SQL file, not a network write — same trade as
 *    build-ingest-sql.mjs, same reason (no live Supabase in the loop environment),
 *    and the same one-line change the day credentials exist.
 *
 * TypeScript is imported directly, with no build step and no new dependency — the
 * registerHooks preamble is copied verbatim from scripts/build-ingest-sql.mjs.
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { registerHooks } from 'node:module';

registerHooks({
  resolve(specifier, context, nextResolve) {
    if (specifier.startsWith('.') && !/\.[a-z]+$/i.test(specifier)) {
      try {
        return withTsFormat(nextResolve(`${specifier}.ts`, context));
      } catch {
        // Not a TypeScript sibling — fall through to the default resolver.
      }
    }
    return withTsFormat(nextResolve(specifier, context));
  },
});

function withTsFormat(resolved) {
  if (resolved && typeof resolved.url === 'string' && resolved.url.endsWith('.ts')) {
    return { ...resolved, format: 'module-typescript' };
  }
  return resolved;
}

const { parseCefrCsv, buildLevelMap } = await import('../lib/core/cefrLevels.ts');
const { assignWordLevels, formatLevelReport, profileSourceOf } = await import('../lib/core/wordLevel.ts');
const { parseBatchFile } = await import('../lib/core/batchRecord.ts');

/** F-048ⓑ · same override, same reason as build-ingest-sql.mjs — see the note there. */
const OUT_DIR = process.env.SEED_OUT_DIR || join('supabase', 'seed');
const OUT = join(OUT_DIR, '0002_word_cefr_levels.sql');
const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replaceAll("'", "''")}'`);

const CEFRJ = 'cefrj-vocabulary-profile-1.5.csv';
const OCTANOVE = 'octanove-vocabulary-profile-c1c2-1.0.csv';

// --- 1. the two profiles ----------------------------------------------------
const cefrj = parseCefrCsv(readFileSync(join('data', CEFRJ), 'utf8'));
const octanove = parseCefrCsv(readFileSync(join('data', OCTANOVE), 'utf8'));
const map = buildLevelMap([...cefrj.entries, ...octanove.entries]);

// --- 2. one row per (headword, pos) -----------------------------------------
// `words` is unique on that pair, and a headword with three senses must not produce
// three conflicting updates. First sense wins; the band written does not come from the
// sense at all, so which sense wins cannot change the band — only the ownBand the
// agreement counter compares it against.
const byKey = new Map();
const batchFiles = readdirSync(join('data', 'generated'))
  .filter((f) => /^batch-.*\.jsonl$/.test(f))
  .sort();
for (const file of batchFiles) {
  for (const rec of parseBatchFile(readFileSync(join('data', 'generated', file), 'utf8'))) {
    const key = `${rec.sense.headword.toLowerCase()}#${rec.sense.pos}`;
    if (!byKey.has(key)) {
      byKey.set(key, {
        headword: rec.sense.headword,
        pos: rec.sense.pos,
        ownBand: rec.cefrLevel ?? null,
      });
    }
  }
}

const report = assignWordLevels(map, [...byKey.values()]);

// ⛔ The band→source rule is NOT decided here: it lives in lib/core/wordLevel.ts, pure
// and unit-tested, because this corpus holds no C1/C2 word and an emitter-level test
// therefore cannot reach the Octanove branch at all.

// --- 3. emit ----------------------------------------------------------------
const lines = [
  '-- GENERATED by scripts/build-word-levels-sql.mjs (T-010). ⛔ Do not hand-edit.',
  `-- Sources: cefr-j-1.5 (${CEFRJ}) · octanove-1.0 (${OCTANOVE})`,
  `-- ${formatLevelReport(report)}`,
  '-- ⛔ UPDATE only. This file never creates a word and never touches the sense-level band.',
  '-- Apply supabase/migrations/0008_word_cefr_profile.sql first.',
  '',
  'begin;',
];
for (const w of report.words) {
  if (w.profileBand === null) continue; // ⛔ no row for a word no profile covers
  lines.push(
    `update public.words set cefr_profile_band = ${q(w.profileBand)}, ` +
      `cefr_profile_source = ${q(profileSourceOf(w.profileBand))} ` +
      `where headword = ${q(w.headword)} and pos = ${q(w.pos)};`,
  );
}
lines.push('commit;', '');

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(OUT, lines.join('\n'), 'utf8');

// --- 4. report --------------------------------------------------------------
console.log(formatLevelReport(report));
console.log(`profiles: cefr-j rows ${cefrj.rows} entries ${cefrj.entries.length} unknownPos ${cefrj.unknownPos} · `
  + `octanove rows ${octanove.rows} entries ${octanove.entries.length} unknownPos ${octanove.unknownPos}`);
console.log(`wrote ${OUT}`);
