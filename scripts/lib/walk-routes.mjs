export const DEFAULT_ROUTES = [
  '/',
  '/dev/onboarding',
  '/dev/tabs/cards',
  '/dev/card/choice',
  '/dev/tabs/studies',
  '/dev/story',
  '/dev/story/live',
  '/dev/arcade/home',
  '/dev/arcade/summary',
  '/dev/amirnet/dashboard',
  '/dev/amirnet/practice',
  '/dev/amirnet/simulation',
  '/dev/world',
  '/dev/tabs/me',
];

/**
 * ⛔ `--routes=` גובר על הרשימה המוצהרת, ⛔ ומחרוזת ריקה ⛔ אינה «אפס מסכים» —
 * היא «⛔ לא נמסר דגל». הפרדה שהייתה משתמעת בסקריפט והופכת כאן לנבדקת.
 */
export function walkRoutes(routesFlag) {
  const raw = (routesFlag || '').trim();
  if (raw === '') return DEFAULT_ROUTES;
  return raw
    .split(',')
    .map((r) => r.trim())
    .filter((r) => r !== '');
}
