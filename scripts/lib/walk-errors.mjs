/** הצורה שבה ההליכה רושמת כשל בקשה. מקור אחד, כדי שהבדיקה ⛔ לא תמציא צורה משלה. */
export const requestFailureLine = (errorText, url) =>
  `REQFAIL ${errorText} ⇐ ${url.slice(0, 140)}`;

/**
 * ⛔ **מעוגן בתחילת השורה ועד המפריד** ⇒ הוא קורא את ה-`errorText` ו⛔ לא את הכתובת.
 * ⇒ `net::ERR_FAILED` על אותו נתיב `_rsc` בדיוק ⛔ **אינו** מסונן.
 */
export const isAbortedRequestLine = (line) =>
  typeof line === 'string' && line.startsWith('REQFAIL net::ERR_ABORTED ⇐ ');

/** ⛔ שתי רשימות, ⛔ ולא מחיקה: `errors` הוא מה שנספר, `aborted` הוא מה שמדווח. */
export const splitAborted = (lines) => ({
  errors: lines.filter((l) => !isAbortedRequestLine(l)),
  aborted: lines.filter((l) => isAbortedRequestLine(l)),
});
