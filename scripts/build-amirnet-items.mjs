#!/usr/bin/env node
/**
 * Builds `supabase/seed/0006_amirnet_items.sql` from `data/generated/amirnet-items-*.jsonl`
 * (T-310 · `41 § 6.5` · the table is `supabase/migrations/0024_amirnet_items.sql`).
 *
 * ⛔ **WHY THIS EXISTS, and it was measured, ⛔ not assumed.** C-0551 (CONTENT) delivered
 * `K-006` — 26 items that passed the real gate 26/26 — into three `.jsonl` files, and
 * C-0553's live walk then measured the consequence: a learner who presses `רמה 1` on
 * `/world/amirnet/simulation` is told «עוד אין מספיק פריטים», because `GET
 * /api/amirnet/simulation` and `GET /api/amirnet/practice` read `public.amirnet_items` and
 * ⛔ nothing ever carried the files into it. The items were written and unreadable.
 *
 * ⛔ **IT TRANSFERS, ⛔ IT DOES NOT WRITE** (`R-010`, extended to amirnet by `RULES § 0.1 ז׳`).
 * ⛔ No field is defaulted, ⛔ no band is inferred, ⛔ no explanation is generated. An item
 * that arrives incomplete is REFUSED — see below — and regenerated by CONTENT, ⛔ never
 * repaired here. Repairing content inside an ingest is a CONTENT tick.
 *
 * ⛔ **THE GATE RUNS AGAIN HERE, ON EVERY ITEM** — the `build-ingest-sql.mjs` rule (`R-014`),
 * and it is the REAL gate (`lib/core/amirnetItemGate.ts` · `lib/core/amirnetChapterGate.ts`),
 * ⛔ never a reconstruction of it. An `rc` chapter is gated as a chapter, because five
 * questions sharing one passage is a property ⛔ no per-item check can see.
 *
 * 🔵 **`vocab_band` MOVED INTO THE GATE — C-0564, closing `F-235`ⓐ.** This block used to
 * say «the gate is ⛔ not enough», because `AmirnetItemRecord` carried ⛔ no `vocab_band`
 * field at all and this script was the only place the column could be measured. ⇒ an item
 * passed the gate 26/26 and was still **unwritable**, and `npm run measure:amirnet-gate`
 * — the command CONTENT and the registers read — reported the bank clean. The field is now
 * part of `AmirnetItemRecord` and `amirnetItemGate()` refuses `bad_vocab_band` against the
 * same closed set `0024`'s check constraint holds, so **both places refuse on the same
 * thing**. Measured on `K-006`: 16 of 26 items complete; the 10 `rc` questions carry no
 * `vocab_band` ⇒ refused, and filed as a finding rather than filled in.
 *
 * ⚠️ **What is still measured HERE and ⛔ not in the gate:** `explanation_he` and
 * `passage_en` — two columns the table requires that `AmirnetItemRecord` does ⛔ not model,
 * because ⛔ neither is a property of a well-formed *question* (`41 § 7` makes the Hebrew
 * explanation a property of a served *row*). ⇒ `shortfall()` shrank; it ⛔ did not go away.
 *
 * ⛔ **A REFUSAL IS LOUD, ⛔ never a silent skip** (T-310ⓑ): every refused item is printed
 * with its id and its reason, and the process exits non-zero — exactly the shape
 * `build-ingest-sql.mjs` has used since T-042. The rows that ARE complete are still emitted:
 * withholding them would punish a learner for a field they cannot see.
 *
 * ⛔ **A SECOND RUN ⛔ DOES NOT DUPLICATE** (T-310ⓒ): the insert ends `on conflict (type,
 * level, stem_en) do nothing`, against the unique key `0024` already declares. The emitted
 * bytes are a pure function of the inputs — the files are read in sorted order and the rows
 * are emitted in file order, so two runs over the same input produce an identical file.
 *
 * `SEED_OUT_DIR` retargets the output (F-048ⓑ): a test that runs this generator must ⛔ not
 * overwrite a git-managed file. The emitted SQL is identical either way.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { registerHooks } from 'node:module';

registerHooks({
  resolve(specifier, context, nextResolve) {
    if (specifier.startsWith('.') && !/\.[a-z]+$/i.test(specifier)) {
      try {
        return withTsFormat(nextResolve(`${specifier}.ts`, context));
      } catch {
        // Not a TypeScript sibling — fall through to the default resolver.
      }
    }
    return withTsFormat(nextResolve(specifier, context));
  },
});

function withTsFormat(resolved) {
  if (resolved && typeof resolved.url === 'string' && resolved.url.endsWith('.ts')) {
    return { ...resolved, format: 'module-typescript' };
  }
  return resolved;
}

const { amirnetItemGate } = await import('../lib/core/amirnetItemGate.ts');
const { amirnetChapterGate } = await import('../lib/core/amirnetChapterGate.ts');

const DATA = process.env.AMIRNET_ITEMS_DIR || join('data', 'generated');
const VOCAB_PATH = process.env.AMIRNET_VOCAB_CSV || join(DATA, 'amirnet-vocab.csv');
const OUT_DIR = process.env.SEED_OUT_DIR || join('supabase', 'seed');
const OUT = join(OUT_DIR, '0006_amirnet_items.sql');

/** A SQL string literal. Doubling the quote is the whole of the escaping. */
const q = (value) => `'${String(value).replaceAll("'", "''")}'`;
const arr = (values) => `array[${values.map(q).join(', ')}]::text[]`;

// --- 1. the vocabulary tiers the gate needs ---------------------------------
// Identical to `measure-amirnet-gate.mjs`: absence degrades to «no ceiling enforced»,
// ⛔ it does not invent one.
function loadVocabTiers(path) {
  const map = new Map();
  if (!existsSync(path)) return map;
  for (const line of readFileSync(path, 'utf8').split('\n').slice(1)) {
    if (line.trim() === '') continue;
    const [headword, , , tier] = line.split(',');
    const t = Number(tier);
    if (headword && t >= 1 && t <= 4) map.set(headword.toLowerCase(), t);
  }
  return map;
}
const vocabTierByWord = loadVocabTiers(VOCAB_PATH);

// --- 2. the files, in sorted order (readdir order is ⛔ not stable) ----------
const files = existsSync(DATA)
  ? readdirSync(DATA)
      .filter((name) => /^amirnet-items-.*\.jsonl$/.test(name))
      .sort()
  : [];

/**
 * ⛔ Provenance is a STOP, ⛔ not a default — the `build-ingest-sql.mjs` rule. An item file
 * that no manifest declares in `output_files` is not ingested at all: `model` and
 * `prompt_version` are how a bad batch is ever traced back, and inventing them would make
 * every later question about this bank unanswerable.
 */
function manifestFor(file) {
  for (const name of readdirSync(DATA).filter((n) => /^amirnet-items-manifest-.*\.json$/.test(n)).sort()) {
    const parsed = JSON.parse(readFileSync(join(DATA, name), 'utf8'));
    if (Array.isArray(parsed.output_files) && parsed.output_files.includes(file)) return { name, parsed };
  }
  throw new Error(`no amirnet manifest declares "${file}" — refusing to ingest an undeclared item file`);
}

// --- 3. flatten to table rows, gate them, and check what the TABLE requires --
const refused = [];
const rows = [];

/**
 * The two columns of `public.amirnet_items` that `AmirnetItemRecord` does ⛔ not model.
 * ⛔ `vocab_band` is ⛔ no longer one of them — it moved into the gate itself in C-0564
 * (`F-235`ⓐ), so a band that is absent or off-set is refused by `amirnetItemGate()` and
 * reaches this script as the reason `bad_vocab_band`.
 */
function shortfall(record) {
  const missing = [];
  if (typeof record.explanationHe !== 'string' || record.explanationHe.trim() === '') {
    missing.push('explanation_he empty (41 § 7 — the Hebrew explanation is ⛔ never generated at read time)');
  }
  if (typeof record.passageEn !== 'string') missing.push('passageEn absent');
  return missing;
}

/**
 * A gate reason, as a line a human can act on. ⛔ Only `bad_vocab_band` needs it: the gate
 * is pure and reports the reason, ⛔ never the offending value, and «which band did it
 * carry» is the first question anyone asks. ⛔ The wording is ⛔ not a second opinion — the
 * refusal already happened, in the gate.
 */
function annotate(reason, record) {
  if (reason !== 'bad_vocab_band') return reason;
  return record.vocab_band === undefined
    ? 'bad_vocab_band — vocab_band absent (41 § 6.5 · 0024 declares it not null) — ⛔ NOT inferred here'
    : `bad_vocab_band — vocab_band ${JSON.stringify(record.vocab_band)} outside 1000 | 2000 | 3000`;
}

for (const file of files) {
  const { name: manifestName, parsed: manifest } = manifestFor(file);
  const lines = readFileSync(join(DATA, file), 'utf8').split('\n').filter((l) => l.trim() !== '');

  lines.forEach((line, i) => {
    const where = `${file}:${i + 1}`;
    const record = JSON.parse(line);

    // An `rc` CHAPTER is five questions under one passage — gated as a chapter (41 § 6.3).
    const isChapter = record.type === 'rc' && Array.isArray(record.questions);
    const candidates = isChapter
      ? record.questions.map((question) => ({
          ...question,
          type: 'rc',
          level: record.level,
          passageEn: record.passageEn,
          source: question.source ?? record.source,
        }))
      : [record];

    if (isChapter) {
      const chapter = amirnetChapterGate(candidates, { vocabTierByWord });
      if (!chapter.ok) {
        // ⛔ `item_<n>_failed` names WHICH question and ⛔ not WHAT is wrong with it, and a
        // refusal nobody can act on is the silent skip T-310ⓑ exists against. The chapter's
        // own reasons apply to all five; each question also carries its own.
        const chapterWide = chapter.reasons.filter((r) => !/^item_\d+_failed$/.test(r));
        candidates.forEach((c, qi) => {
          const own = (chapter.perQuestion[qi]?.reasons ?? []).map((r) => annotate(r, c));
          refused.push({ where, id: c.id, why: ['chapter', ...chapterWide, ...own].join(' · ') });
        });
        return;
      }
    }

    for (const candidate of candidates) {
      const gate = isChapter ? { ok: true, reasons: [] } : amirnetItemGate(candidate, { vocabTierByWord });
      const missing = shortfall(candidate);
      if (!gate.ok || missing.length > 0) {
        const why = [...gate.reasons.map((r) => annotate(r, candidate)), ...missing];
        refused.push({ where, id: candidate.id, why: why.join(' · ') });
        continue;
      }
      rows.push({
        manifest: manifestName,
        model: manifest.model,
        promptVersion: manifest.prompt_version,
        type: candidate.type,
        level: candidate.level,
        stemEn: candidate.stemEn,
        passageEn: candidate.passageEn,
        optionsEn: candidate.options.map((o) => o.textEn),
        correctIndex: candidate.correctIndex,
        distractorReasons: candidate.options.map((o) => o.reason),
        explanationHe: candidate.explanationHe,
        levelRationale: candidate.levelRationale,
        vocabBand: candidate.vocab_band,
        source: candidate.source,
      });
    }
  });
}

// ⛔ The unique key `0024` declares. Two identical stems at the same type and level would
// silently collapse to one row on insert — that is a data defect in the delivery, ⛔ not
// something `on conflict do nothing` should absorb quietly.
const seen = new Map();
for (const row of rows) {
  const key = `${row.type}|${row.level}|${row.stemEn}`;
  if (seen.has(key)) refused.push({ where: '—', id: row.stemEn.slice(0, 40), why: `duplicate of ${seen.get(key)} under unique (type, level, stem_en)` });
  else seen.set(key, row.stemEn.slice(0, 40));
}

// --- 4. emit ----------------------------------------------------------------
const manifests = [...new Set(rows.map((r) => `${r.manifest} (${r.model} · ${r.promptVersion})`))].sort();
const lines = [
  '-- 0006_amirnet_items.sql — GENERATED by scripts/build-amirnet-items.mjs (T-310).',
  '-- ⛔ Never hand-edit: regenerate with `npm run build:amirnet-items`.',
  '--',
  '-- Source: data/generated/amirnet-items-*.jsonl (commission K-006).',
  ...manifests.map((m) => `--   manifest ${m}`),
  '-- Every row below passed lib/core/amirnetItemGate.ts (rc: amirnetChapterGate.ts) in THIS',
  '-- build, ⛔ not in a reconstruction of it, and carries every column 0024 declares not null.',
  '-- ⛔ Items the build refused are ⛔ NOT here and were ⛔ NOT repaired — see the build output.',
  '--',
  '-- Re-runnable: `on conflict (type, level, stem_en) do nothing` against the unique key',
  '-- 0024_amirnet_items.sql declares. A second apply inserts ⛔ nothing.',
  '',
  'begin;',
  '',
];

if (rows.length > 0) {
  lines.push(
    'insert into public.amirnet_items',
    '  (type, level, stem_en, passage_en, options_en, correct_index, distractor_reasons,',
    '   explanation_he, level_rationale, vocab_band, source)',
    'values',
  );
  lines.push(
    rows
      .map(
        (r) =>
          `  (${q(r.type)}, ${r.level}, ${q(r.stemEn)}, ${q(r.passageEn)}, ${arr(r.optionsEn)},\n` +
          `   ${r.correctIndex}, ${arr(r.distractorReasons)}, ${q(r.explanationHe)},\n` +
          `   ${q(r.levelRationale)}, ${r.vocabBand}, ${q(r.source)})`,
      )
      .join(',\n'),
  );
  lines.push('on conflict (type, level, stem_en) do nothing;', '');
} else {
  lines.push('-- ⛔ Zero complete items in this build. ⛔ No insert is emitted.', '');
}

lines.push('commit;', '');

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(OUT, lines.join('\n'), 'utf8');

// --- 5. report --------------------------------------------------------------
const byType = (t) => rows.filter((r) => r.type === t).length;
console.log(`${files.length} amirnet item files read from ${DATA}`);
console.log(`${rows.length} items emitted — sc ${byType('sc')} · rs ${byType('rs')} · rc ${byType('rc')}`);
console.log(`${refused.length} items REFUSED (⛔ excluded, ⛔ not repaired)`);
console.log(`wrote ${OUT}`);

if (refused.length > 0) {
  console.error('');
  console.error('⛔ refused items are EXCLUDED from the SQL and are ⛔ NOT repaired here —');
  console.error('⛔ a missing field is regenerated by CONTENT (R-010), ⛔ never filled in by this script:');
  for (const r of refused) console.error(`   ${r.where} ${r.id} — ${r.why}`);
  process.exit(1);
}
