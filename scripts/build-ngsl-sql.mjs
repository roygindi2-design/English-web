#!/usr/bin/env node
/**
 * Builds supabase/seed/0008_ngsl_frequency.sql from data/ngsl-1.2.csv (T-007 · 10-pedagogy
 * 1.3.1 S1 · T-012 · F-005).
 *
 * ⛔ **WHY THIS EXISTS.** `words.ngsl_rank` was created in `0002_content_bank.sql` as the
 *    frequency backbone, and three routes already order by it (`study/queue` · `arcade/round`
 *    · `world/recall`). Measured on the live database in C-0829: 1,559 words, **0** with a
 *    rank ⇒ every one of those orders fell through to its tie-break. The source list arrived
 *    in C-0768 (Roy's approval, official domain only — R-004) and nothing read it.
 *
 * ⛔ **WHY A TABLE OF ITS OWN, ⛔ AND ⛔ NOT 2,809 ROWS IN `words`.** `words.pos` is
 *    `not null` and the key is `(headword, pos)`; NGSL v1.2 carries ⛔ no part of speech.
 *    Writing its lemmas into `words` would mean inventing one per row (R-010). ⇒ the list
 *    lives whole in `ngsl_frequency` (`0040`), and `words` receives only the RANK, by headword.
 *
 * ⛔ **Zero authored content:** rank · headword · SFI exactly as the site publishes them.
 *    `u_per_million` stays in the CSV — T-007 names three columns, ⛔ not four.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

/** T-012 · F-005 — v1.2 is 2,809 lemmas. 2,801 is the early list from R-004's bad domain. */
export const NGSL_ROWS = 2809;

const CSV = process.env.NGSL_CSV || join('data', 'ngsl-1.2.csv');
/** F-048ⓑ — a test points this at a throwaway directory and COMPARES; ⛔ never clobbers. */
const OUT_DIR = process.env.SEED_OUT_DIR || join('supabase', 'seed');
const OUT = join(OUT_DIR, '0008_ngsl_frequency.sql');

const q = (value) => `'${String(value).replaceAll("'", "''")}'`;

/** The file has no quoted fields (measured: 0 quotes, 0 embedded commas) — split is enough. */
export function parseNgslCsv(text) {
  const rows = [];
  let header = null;
  for (const line of text.split(/\r?\n/)) {
    if (line.trim() === '') continue;
    const cols = line.split(',').map((c) => c.trim());
    if (header === null) {
      header = cols;
      continue;
    }
    const cell = (name) => cols[header.indexOf(name)] ?? '';
    rows.push({ rank: Number(cell('rank')), headword: cell('headword'), sfi: Number(cell('sfi')) });
  }
  return rows;
}

/** Every gate `0040_ngsl_frequency.sql` states, refused here by name before it is SQL. */
function refuseUnwritable(rows) {
  if (rows.length !== NGSL_ROWS) {
    throw new Error(`NGSL v1.2 is exactly 2,809 rows — got ${rows.length} (T-012 · F-005)`);
  }
  const seen = new Set();
  rows.forEach((row, i) => {
    const at = `row ${i + 1} "${row.headword}"`;
    if (row.rank !== i + 1) throw new Error(`${at} — rank ${row.rank}, expected ${i + 1} (ranks are 1…2809, in order)`);
    if (row.headword.length === 0 || row.headword !== row.headword.trim()) {
      throw new Error(`${at} — a blank or padded headword (ngsl_frequency_headword_check)`);
    }
    const key = row.headword.toLowerCase();
    if (seen.has(key)) throw new Error(`${at} — duplicate headword ${row.headword}`);
    seen.add(key);
    if (!Number.isFinite(row.sfi) || row.sfi <= 0 || row.sfi >= 100) {
      throw new Error(`${at} — sfi ${row.sfi} is outside (0, 100) (ngsl_frequency_sfi_check)`);
    }
  });
}

/** Pure: rows in, SQL text out. ⛔ No clock, no randomness ⇒ same rows, same bytes. */
export function toNgslSql(rows) {
  refuseUnwritable(rows);

  // `unnest … with ordinality` makes the rank the array position, which the gate above
  // has just proven equal to the published rank — so the file carries each value once.
  const headwords = rows.map((r) => q(r.headword));
  const sfis = rows.map((r) => r.sfi.toFixed(2));
  const chunk = (items) => {
    const out = [];
    for (let i = 0; i < items.length; i += 20) out.push(`    ${items.slice(i, i + 20).join(',')}`);
    return out.join(',\n');
  };

  return [
    '-- supabase/seed/0008_ngsl_frequency.sql',
    '-- ⛔ GENERATED by scripts/build-ngsl-sql.mjs — do not edit by hand.',
    '--    Regenerate with `npm run build:ngsl-sql`. Apply after 0040_ngsl_frequency.sql.',
    '--',
    `-- ${rows.length} rows · NGSL v1.2 (Browne, Culligan & Phillips · CC BY-SA 4.0), fetched from`,
    '-- newgeneralservicelist.com only (R-004 · data/README.md). ⛔ Zero authored content (R-010).',
    '-- Re-runnable: the insert is `on conflict (rank) do nothing` and both updates are no-ops',
    '-- on a second load. Re-run it after an ingest adds words, so new headwords get a rank.',
    '',
    'begin;',
    '',
    'insert into public.ngsl_frequency (rank, headword, sfi)',
    'select t.rank::int, t.headword, t.sfi',
    'from unnest(',
    '  array[',
    chunk(headwords),
    '  ]::text[],',
    '  array[',
    chunk(sfis),
    '  ]::numeric[]',
    ') with ordinality as t(headword, sfi, rank)',
    'on conflict (rank) do nothing;',
    '',
    '-- T-007 — the backbone: every word whose headword is an NGSL lemma takes its rank.',
    '-- NGSL has no part of speech ⇒ all rows of one headword share the lemma\'s rank.',
    'update public.words w',
    '   set ngsl_rank = n.rank',
    '  from public.ngsl_frequency n',
    ' where lower(w.headword) = lower(n.headword)',
    '   and w.ngsl_rank is distinct from n.rank;',
    '',
    '-- F-281 · T-411 — a bookmark written while every rank was NULL says «inside the unranked',
    '-- tail», and that predicate would now skip every ranked word in the band. Re-anchor it',
    '-- to the rank its own last word now carries (still NULL for a word NGSL does not list).',
    'update public.study_level_cursor c',
    '   set last_ngsl_rank = w.ngsl_rank',
    '  from public.words w',
    ' where w.id = c.last_word_id',
    '   and c.last_ngsl_rank is distinct from w.ngsl_rank;',
    '',
    'commit;',
    '',
  ].join('\n');
}

const isMain = import.meta.url === `file://${process.argv[1]}`;

if (isMain) {
  const rows = parseNgslCsv(readFileSync(CSV, 'utf8'));
  const sql = toNgslSql(rows);
  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(OUT, sql, 'utf8');
  console.log(`${rows.length} rows read from ${CSV}`);
  console.log(`wrote ${OUT}`);
}
