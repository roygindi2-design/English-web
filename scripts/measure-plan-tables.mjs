#!/usr/bin/env node
/**
 * F-050 + F-056, mechanised — "is there Dev-eligible work, and is any ⛔ cell stale?"
 * in one command.
 *
 * ⛔ Read-only over plan/. The two files it writes are docs/plan-tables.md (the shape
 * report) and docs/plan-open.md (T-184's work index).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { registerHooks } from 'node:module';

registerHooks({
  resolve(specifier, context, nextResolve) {
    if (specifier.startsWith('.') && !/\.[a-z]+$/i.test(specifier)) {
      try {
        return withTsFormat(nextResolve(`${specifier}.ts`, context));
      } catch {
        // Not a TypeScript sibling — fall through to the default resolver.
      }
    }
    return withTsFormat(nextResolve(specifier, context));
  },
});

function withTsFormat(resolved) {
  if (resolved && typeof resolved.url === 'string' && resolved.url.endsWith('.ts')) {
    return { ...resolved, format: 'module-typescript' };
  }
  return resolved;
}

const {
  rowShape,
  classifyStatus,
  staleBlocks,
  staleTaskBlocks,
  eligibleTaskIds,
  citedTasks,
  excerpt,
  BLOCKER_MARKER,
  TASK_COLUMNS,
  FINDING_COLUMNS,
  TASK_STATUS_INDEX,
  FINDING_STATUS_INDEX,
} = await import('../lib/core/planTable.ts');

const TASKS_FILE = join('plan', '50-tasks.md');
const FINDINGS_FILE = join('plan', '60-findings.md');
const OUT = process.env.PLAN_TABLES_OUT || join('docs', 'plan-tables.md');
const OPEN_OUT = process.env.PLAN_OPEN_OUT || join('docs', 'plan-open.md');

const shapesOf = (file, columns) =>
  readFileSync(file, 'utf8')
    .split('\n')
    .map((line) => rowShape(line, columns))
    .filter((shape) => shape !== null);

const taskRows = shapesOf(TASKS_FILE, TASK_COLUMNS);
const findingRows = shapesOf(FINDINGS_FILE, FINDING_COLUMNS);

const findingStates = new Map();
for (const row of findingRows) {
  if (!row.ok) continue;
  const cell = row.cells[FINDING_STATUS_INDEX];
  if (cell !== undefined) findingStates.set(row.id, classifyStatus(cell));
}

const badTasks = taskRows.filter((r) => !r.ok);
const badFindings = findingRows.filter((r) => !r.ok);
const eligible = eligibleTaskIds(taskRows);
const stale = staleBlocks(taskRows, findingStates);
const staleTasks = staleTaskBlocks(taskRows);

const shapeLine = (r) => `| \`${r.id}\` | ${r.cells.length} | ${r.expected} |`;
const report = [
  '<!-- GENERATED by scripts/measure-plan-tables.mjs — ⛔ do not edit by hand. -->',
  '',
  '# מצב הרגיסטרים — קריאה מכונה',
  '',
  `- \`${TASKS_FILE}\`: ${taskRows.length} שורות, ${badTasks.length} פגומות`,
  `- \`${FINDINGS_FILE}\`: ${findingRows.length} שורות, ${badFindings.length} פגומות`,
  '',
  '## שורות שאינן נקראות לפי עמודה',
  '',
  '| שורה | תאים בפועל | תאים בכותרת |',
  '|---|---|---|',
  ...[...badTasks, ...badFindings].map(shapeLine),
  '',
  '## משימות פנויות ל-Dev (⬜)',
  '',
  eligible.length === 0 ? '⛔ אין.' : eligible.map((id) => `- \`${id}\``).join('\n'),
  '',
  '## חסמים ⛔ שמצטטים ממצא סגור',
  '',
  stale.length === 0
    ? '⛔ אין.'
    : stale.map((s) => `- \`${s.taskId}\` מצטטת \`${s.findingId}\`, שסטטוסה \`done\``).join('\n'),
  '',
  '## חסמים ⛔ שמצטטים משימה שכבר נמסרה',
  '',
  staleTasks.length === 0
    ? '⛔ אין.'
    : staleTasks
        .map((s) => `- \`${s.taskId}\` ממתינה ל-\`${s.blockerId}\`, שסטטוסה \`${s.blockerState}\``)
        .join('\n'),
  '',
].join('\n');

writeFileSync(OUT, report, 'utf8');

/* ─────────────────────────────────────────────────────────────────────────────
 * T-184 · docs/plan-open.md — the work index.
 *
 * MEASURED, and it is the whole reason this half exists: plan/50-tasks.md is 405,516
 * bytes and plan/60-findings.md is 261,727. Every Dev, PM and Critic tick read both,
 * whole ⇒ ~200k tokens of reading before any work. 89 of 200 task rows are ✅ and 62 of
 * 117 finding rows are closed, so more than half of that is history no agent acts on.
 *
 * ⛔ This file is a POINTER, not a source of truth, and it says so in its own header:
 * every cell is an excerpt, and the full row is one `grep` away. An agent that decides
 * from the excerpt alone is doing the same thing as an agent that reads a stale plan.
 *
 * ⛔ ✅ and 🚫 are the ONLY two states dropped. Anything unrecognised (a new glyph, a
 * malformed row) stays IN — an index that silently swallows a row it cannot classify is
 * worse than no index, because the row stops existing for every agent at once.
 * ───────────────────────────────────────────────────────────────────────────── */

const TITLE_CHARS = 150;
const NOTE_CHARS = 110;

const taskState = (row) =>
  row.ok ? classifyStatus(row.cells[TASK_STATUS_INDEX] ?? '') : 'malformed';
const findingState = (row) =>
  row.ok ? classifyStatus(row.cells[FINDING_STATUS_INDEX] ?? '') : 'malformed';

const CLOSED = new Set(['done', 'cancelled']);
const openTasks = taskRows.filter((r) => !CLOSED.has(taskState(r)));
const openFindings = findingRows.filter((r) => !CLOSED.has(findingState(r)));

const blockerOf = (row) => {
  const cell = row.cells[TASK_STATUS_INDEX] ?? '';
  const declared = citedTasks(cell, row.id);
  if (declared.length > 0) return `\`${declared.join('` · `')}\``;
  const at = cell.indexOf(BLOCKER_MARKER);
  return excerpt(at === -1 ? cell : cell.slice(at + BLOCKER_MARKER.length), NOTE_CHARS);
};

const taskSection = (title, state, columns, rowLine) => {
  const rows = openTasks.filter((r) => taskState(r) === state);
  return [
    `## ${title} (${rows.length})`,
    '',
    ...(rows.length === 0
      ? ['⛔ אין.']
      : [
          `| id | אבן דרך | ${columns} |`,
          `|---|---|${'---|'.repeat(columns.split(' | ').length)}`,
          ...rows.map(rowLine),
        ]),
    '',
  ];
};

const index = [
  '<!-- GENERATED by scripts/measure-plan-tables.mjs — ⛔ do not edit by hand. -->',
  '',
  '# אינדקס העבודה הפתוחה',
  '',
  '⛔ **זהו תקציר, לא מקור אמת.** כל תא כאן חתוך. הטקסט המלא של שורה נמצא ברגיסטר,',
  'בפקודה אחת ובלי לקרוא את הקובץ כולו:',
  '',
  '```bash',
  "grep -n '^| T-185 |' plan/50-tasks.md",
  "grep -n '^| F-093 |' plan/60-findings.md",
  '```',
  '',
  '⛔ החלטה שנשענת על התקציר בלבד היא החלטה על מידע חסר. קרא את השורה המלאה של המשימה',
  'שבחרת **לפני** שאתה נוגע בקוד.',
  '',
  `נוצר מ-\`${TASKS_FILE}\` (${taskRows.length} שורות, ${openTasks.length} פתוחות) ו-\`${FINDINGS_FILE}\` (${findingRows.length} שורות, ${openFindings.length} פתוחים).`,
  '',
  ...taskSection('⬜ פנויות ל-Dev', 'open', 'המשימה (תקציר) | סקיל', (r) =>
    `| \`${r.id}\` | ${excerpt(r.cells[1] ?? '', 12)} | ${excerpt(r.cells[2] ?? '', TITLE_CHARS)} | ${excerpt(r.cells[7] ?? '', 40)} |`,
  ),
  ...taskSection('⛔ חסומות', 'blocked', 'המשימה (תקציר) | חסם', (r) =>
    `| \`${r.id}\` | ${excerpt(r.cells[1] ?? '', 12)} | ${excerpt(r.cells[2] ?? '', TITLE_CHARS)} | ${blockerOf(r)} |`,
  ),
  ...taskSection('🟣 בתור הביקורת', 'awaiting-review', 'המשימה (תקציר) | נמסרה', (r) =>
    `| \`${r.id}\` | ${excerpt(r.cells[1] ?? '', 12)} | ${excerpt(r.cells[2] ?? '', TITLE_CHARS)} | ${excerpt(r.cells[TASK_STATUS_INDEX] ?? '', NOTE_CHARS)} |`,
  ),
  ...taskSection('❔ סטטוס שאינו מזוהה — ⛔ טפל בו', 'unknown', 'המשימה (תקציר) | תא הסטטוס', (r) =>
    `| \`${r.id}\` | ${excerpt(r.cells[1] ?? '', 12)} | ${excerpt(r.cells[2] ?? '', TITLE_CHARS)} | ${excerpt(r.cells[TASK_STATUS_INDEX] ?? '', NOTE_CHARS)} |`,
  ),
  ...taskSection('⚠️ שורות משימה פגומות — ⛔ אינן נקראות לפי עמודה', 'malformed', 'תאים', (r) =>
    `| \`${r.id}\` | — | ${r.cells.length} מתוך ${r.expected} |`,
  ),
  `## ממצאים פתוחים (${openFindings.length})`,
  '',
  ...(openFindings.length === 0
    ? ['⛔ אין.']
    : [
        '| id | חומרה | קובץ | הממצא (תקציר) | סטטוס |',
        '|---|---|---|---|---|',
        ...openFindings.map((r) =>
          r.ok
            ? `| \`${r.id}\` | ${excerpt(r.cells[1] ?? '', 14)} | ${excerpt(r.cells[2] ?? '', 46)} | ${excerpt(r.cells[3] ?? '', TITLE_CHARS)} | ${excerpt(r.cells[FINDING_STATUS_INDEX] ?? '', 40)} |`
            : `| \`${r.id}\` | ⚠️ פגומה | ${r.cells.length} מתוך ${r.expected} תאים | ${excerpt(r.cells[3] ?? '', TITLE_CHARS)} | — |`,
        ),
      ]),
  '',
].join('\n');

writeFileSync(OPEN_OUT, index, 'utf8');

console.log(`tasks: ${taskRows.length} rows, ${badTasks.length} malformed`);
console.log(`findings: ${findingRows.length} rows, ${badFindings.length} malformed`);
console.log(`eligible: ${eligible.length === 0 ? 'none' : eligible.join(' ')}`);
if (stale.length === 0) console.log('stale blockers: none');
for (const s of stale) console.log(`stale blockers: ${s.taskId} cites ${s.findingId} (closed)`);
if (staleTasks.length === 0) console.log('stale task blockers: none');
for (const s of staleTasks) {
  console.log(`stale task blockers: ${s.taskId} waits on ${s.blockerId} (${s.blockerState})`);
}
console.log(`open index: ${openTasks.length} tasks, ${openFindings.length} findings`);
console.log(`wrote ${OUT}`);
console.log(`wrote ${OPEN_OUT}`);
