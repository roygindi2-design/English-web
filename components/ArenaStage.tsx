export interface ArenaStageProps {
  readonly phase: StagePhase;
  readonly items: readonly string[];
  /** ⛔ ברירת המחדל היא `ARENA_IDLE_LOOP`. הבמה נשארת **ציור טהור**. */
  readonly idle?: boolean;
  /** T-217 — הדמות שנבחרה (`37 § 7`), מועברת לגיבור בלבד. */
  readonly character?: ArenaCharacter | null;
  /**
   * 🏃 **`T-433`ⓑ · `37 § 5` — הנתיב שהלומד עומד בו, כ-prop.**
   *
   * ⛔ **`null` ⛔ אינו «מרכז» — הוא «עוד לא בחר».** הליבה מבדילה ביניהם
   * (`heroLane: null` ⇒ היריב **עוקב** אחרי הלומד ⇒ ⛔ אין נתיב בטוח), ⛔ אבל
   * ה**ציור** של השניים זהה: הדמות עומדת באמצע. ⇒ ההמרה כאן, ⛔ ולא בליבה.
   */
  readonly lane?: Lane | null;
  /**
   * 🔥 **`T-434` · `37 § 6` — הנתיב שהמתקפה מכוונת אליו, או `null` כשאין מתקפה.**
   *
   * 🔴 **זה ה**מידע**, ⛔ ולא הקישוט.** הסימן על הרצפה הוא **מצב** — תכונה על
   * צומת, ⛔ אפס אנימציה — ⇒ הוא נראה **בדיוק אותו דבר** תחת `prefers-reduced-motion`.
   * ⛔ אילו ההתחמקות הייתה תלויה בכדור הנוסע, לומד עם תנועה מופחתת ⛔ לא היה
   * יכול לשחק.
   */
  readonly aim?: Lane | null;
  /**
   * 🛡️ **`T-438` · `D-270` ① — הנתיב שההגנה המוצבת יושבת בו, או `null`.**
   *
   * 🔴 **והיא **מידע**, ⛔ ולא קישוט** — בדיוק כמו סימן הרצפה: צומת **שקיים
   * או לא קיים**, ⛔ אפס אנימציה. ⇒ לומד עם `prefers-reduced-motion` רואה
   * בדיוק אותו דבר, ויודע היכן הוא מוגן.
   */
  readonly guard?: Lane | null;
  /**
   * 🙌 **`T-440` · `37 § 6` — שלב הטלגרף, כדי שהיריב **יזוז**.**
   *
   * 🔬 **הסעיף כותב את זה במפורש, ו⛔ מעולם ⛔ לא נבנה:** «הכרזה 5.3 ש׳:
   * **ידיים מורמות**, גוון סגול, המד מהבהב». ⇒ עד היום היריב עמד ללא ניע
   * חמש שניות, ו**רק מד** זז.
   */
  readonly telegraph?: 'quiet' | 'charging' | 'window' | 'committed';
  /**
   * 🔥 **⟦20/09 · `C-0750` · `37 § 8` ק1 · `D-271`⟧ הלומד ברצף — וזו **הכרה**,
   * ⛔ ולא נזק.**
   *
   * ‏`D-271` מחק את «מכפיל 1.5» מק1 אחרי שנמדד ש**נזק ומילים הם אותו ציר,
   * הפוך** — תגמול רצף בנזק חותך את הלמידה לחצי דווקא ללומד המדויק ביותר.
   * ⇒ מה שנשאר משלושת הפריטים של ק1 הוא **הילה** ו**להב לוהט**, ושניהם
   * ⛔ אינם נוגעים ב-`cast()`.
   *
   * ⛔ **הסף ⛔ אינו נכתב כאן:** `STREAK_HOT` חי ב-`lib/core/battle.ts` ומצטט
   * את `render_video_B.py:374`, והרכיב שמעל הוא שמחשב אותו — בדיוק כמו
   * שבב הרצף, שכבר משתמש באותו מספר.
   */
  readonly hot?: boolean;
}

/**
 * ⛔ `h-full w-full`, ⛔ ולא `aspect-[4/3]`. 🔬 **נמדד:** יחס גובה-רוחב בתוך הורה
 * `flex-1` הוא הגדרה מעגלית — גובה הילד נגזר מרוחבו, וגובה ההורה נגזר מהילד ⇒
 * **שניהם קרסו ל-20px**, והסט נצבע כפס דק. ⇒ הבמה **ממלאת** את מה שההורה נתן לה,
 * וההורה הוא זה שבולע את הנותר (`flex-1 min-h-0`). הגובה נגזר **כלפי מטה**, ⛔ ולא
 * משני הכיוונים בו-זמנית.
 */
const STAGE_CLASS = 'relative h-full w-full overflow-hidden rounded-xl';

/**
 * 🔴 **⛔ שתי הדמויות נשארות באותו רוחב נומינלי, וזה ⛔ אינו סגנון — זו פיזיקה.**
 *
 * 🔬 **נתפס ע"י הבדיקה, ⛔ ולא על ידי:** `ArenaBattle.test.ts` גוזר את משרעת
 * תנועת-ההמשך (`--arena-follow-x`) מ**רוחב הדמות כאן**: התזוזה של הגוף היא `rem` על
 * ה-`<svg>`, והפיגור חי **בתוך** ה-`viewBox` ביחידות משתמש ⇒ ההמרה היא
 * `BODY_SHIFT_REM / FIGURE_W_REM × VIEW_W`. ⛔ **הקטנת היריב ל-`w-16` הייתה משנה את
 * המכנה מ-6 ל-4 ⇒ 25 יחידות הופכות ל-37.5, ו-`--arena-follow-x: 8.33px` נעשה שקר.**
 *
 * ⇒ **העומק מושג ב-`scale` על העוטף, ⛔ ולא בקופסה קטנה יותר.** זה גם **נכון פיזיקלית**
 * ⛔ ולא רק נוח: דמות רחוקה מוקטנת **על כל מה שבה** — כולל תנועת ההמשך שלה — וזה
 * בדיוק מה שעין מצפה לו. ⇒ ארבעת הפרימיטיבים של הבדיקה נשארים שלמים.
 */
const FIGURE_CLASS = 'h-24 w-24';

