/** D-062: בתוך הזירה, «ידועה» = נענתה נכון ≥3 פעמים בקרבות. ⛔ הקבוע חי כאן בלבד. */
export const ARCADE_KNOWN_CORRECT_MIN = 3;

export function isKnownInArcade(row: { readonly timesCorrect: number }): boolean {
  return row.timesCorrect >= ARCADE_KNOWN_CORRECT_MIN;
}

/**
 * ⛔ מחזירה **מאגר** של מזהים, ⛔ ולא סיבוב: אין כאן הגרלה, אין חיתוך לגודל ואין סדר
 * מוכרע. T-103 היא שבונה את הסיבוב, והיא חסומה עד שהמודול הזה קיים.
 */
export function fluencyPool(
  rows: readonly { readonly wordId: string; readonly timesCorrect: number }[],
): readonly string[] {
  return rows.filter(isKnownInArcade).map((r) => r.wordId);
}
